# WAP to create the multiplication table of a given number

num = int(input("Enter a number: "))  # User input
for i in range(1, 11):
    print(f"{num} x {i} = {num * i}")
    
    
# WAP to print square of n natural numbers

num = int(input("Enter a number: "))  # User input
for i in range(1, num+1):
    print(f"{i} square {i**2}")
    
# WAP to print cube of n natural numbers

num = int(input("Enter a number: "))  # User input
for i in range(1, num+1):
    print(f"{i} cube {i**3}")
    

